def run():
 qs=[json.loads(s) for s in (ROOT/'data/variants/batches/b003/g9.jsonl').read_text(encoding='utf-8').splitlines()]
 ps=[json.loads(s) for s in (ROOT/'data/variants/batches/b003/parents_g9.jsonl').read_text(encoding='utf-8').splitlines()]
 assert len(qs)==len(ps)==len(REVIEWS)==70
 rec=[]
 for i,(q,p,(ans,deriv,bound)) in enumerate(zip(qs,ps,REVIEWS),1):
  issues=[]
  if q['answer']!=ans:issues.append('候选答案与题面独立推导不一致')
  if q['parent_id']!=p['id'] or q['family_id']!=p['family_id']:issues.append('母题顺序或题族不一致')
  if q['grade']!=p['grade'] or q['module']!=p['module']:issues.append('知识模块或年级不一致')
  if q['question']==p['question']:issues.append('题面未作实质修改')
  if q['input_modality']!='text' or q['image_assets']:issues.append('非纯文字')
  if any(x in q['question'] for x in ['如图','ImageHere','<img']):issues.append('缺少的图形引用')
  try:
   matches,_=check_spec(q['verification_spec'])
   if matches!=[ans]:issues.append('算式校验与独立答案不一致')
  except Exception as e:issues.append('verification_spec异常:'+str(e))
  # Version checks ensure prior findings have actually been resolved before pass.
  if i==4 and '完整集合' not in q['question']:issues.append('004未修复所有可能值的唯一性措辞')
  if i==7 and q['options']['C']!='pr=qs':issues.append('007未修复等价干扰项')
  if i==12 and q['verification_spec']['derived_expr'].find('48>0')>=0:issues.append('012垂直判据仍仅测试正长度')
  if i in [13,14,15] and '圆心' not in q['options']['D']:issues.append('圆位置D题文与center机器判据不对应')
  if i==54 and q['difficulty']!='中等':issues.append('054实际常规任务未调整为中等')
  if i==66 and q['options']['D']!='D盒：5黑5白':issues.append('066未同步概率不同值的D选项')
